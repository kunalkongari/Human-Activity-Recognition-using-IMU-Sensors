# 6. MAIN INFERENCE LOOP
# ─────────────────────────────────────────────
def main():
    sensor_buffer = []

    print("=" * 40)
    print("  HAR TinyML — System Ready")
    print("  Target: %d Hz | Window: %d samples" % (SAMPLING_HZ, WINDOW_SIZE))
    print("=" * 40)

    # Brief startup blink
    blue_led.on()
    time.sleep(1)
    blue_led.off()

    while True:
        # --- Sensor Read ---
        accel = lsm.accel()   # (ax, ay, az)  [g]
        gyro  = lsm.gyro()    # (gx, gy, gz)  [dps]
        sensor_buffer.append(accel + gyro)

        # Maintain a fixed-length sliding window
        if len(sensor_buffer) > WINDOW_SIZE:
            sensor_buffer.pop(0)

        # --- Inference (only when window is full) ---
        if len(sensor_buffer) == WINDOW_SIZE:
            features = build_feature_vector(sensor_buffer)

            try:
                probs        = score(features)
                pred_idx     = probs.index(max(probs))
                confidence   = max(probs)
                activity     = ACTIVITY_MAP.get(pred_idx, "Unknown")

                print("Activity: %-20s | Confidence: %.0f%% | Class: %d"
                      % (activity, confidence * 100, pred_idx))

                set_leds(pred_idx)

            except Exception as err:
                print("Inference error:", err)

        time.sleep_ms(SLEEP_MS)


# ─────────────────────────────────────────────
main()
