def set_leds(activity_idx):
    """Drive LED color based on predicted activity class."""
    red_led.off()
    green_led.off()
    if activity_idx in LOW_MOTION_CLASSES:
        green_led.on()   # Sedentary → green
    else:
        red_led.on()     # Active    → red


