def compute_axis_features(data):
    """
    Computes 10 time-domain statistical features for a single sensor axis.

    Features (in order):
        mean, min, max, std, variance, rms, energy, median, iqr, zcr

    Parameters
    ----------
    data : list[float]  — raw sensor readings for one axis across the window

    Returns
    -------
    list[float]  — 10 feature values
    """
    n    = len(data)
    mean = sum(data) / n

    sq_diff  = [(x - mean) ** 2 for x in data]
    variance = sum(sq_diff) / n
    std      = math.sqrt(variance)

    energy = sum(x ** 2 for x in data)
    rms    = math.sqrt(energy / n)

    sorted_data = sorted(data)
    median      = sorted_data[n // 2]
    iqr         = sorted_data[int(n * 0.75)] - sorted_data[int(n * 0.25)]

    # Zero-crossing rate relative to the mean
    zcr = sum(
        1 for i in range(1, n)
        if (data[i] - mean) * (data[i - 1] - mean) < 0
    )

    return [mean, min(data), max(data), std, variance, rms, energy, median, iqr, zcr]


def build_feature_vector(window):
    """
    Builds the full 66-element feature vector from a sliding window.

    Structure:
        • 6 axes × 10 features = 60 statistical features
        • 6 raw values from the most-recent sample (last-value context)
        Total = 66 features

    Parameters
    ----------
    window : list[tuple]  — list of (ax, ay, az, gx, gy, gz) readings

    Returns
    -------
    list[float]  — 66-element feature vector ready for inference
    """
    features = []
    for axis in range(6):  # ax, ay, az, gx, gy, gz
        axis_data = [sample[axis] for sample in window]
        features.extend(compute_axis_features(axis_data))

    # Append the 6 instantaneous sensor values from the latest sample
    features.extend(list(window[-1]))
    return features


